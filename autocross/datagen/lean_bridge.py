"""Export the manifest interchange, run the Lean checker on a corpus, kernel-check the per-sample
witnesses, and run the axiom audit.

Verification layers (all must pass; ``lean_report.json`` records each):
  1. ``lake build``: the theorems of ``lean/Corpus`` are checked by the Lean kernel.
  2. Axiom audit (``Corpus/Audit.lean``): every listed theorem depends only on propext,
     Classical.choice, Quot.sound (no sorryAx, no Lean.ofReduceBool).
  3. ``corpuscheck`` (compiled Lean): reads the manifest interchange and EVERY sample record of the
     corpus directly, quantises each policy observation itself and evaluates ``Cert.decide``; the
     clean-sample set must equal the set of clean samples with a verified certified label.
  4. Kernel witnesses: ``corpuscheck --witness`` writes one theorem ``Cert.decide c q = d`` per
     clean sample (``q`` quantised by Lean, ``d`` the recorded decision); each is proved
     ``by decide``, i.e. checked by the Lean kernel, and its axioms are audited.

Files written: ``<corpus>/lean/interchange.json`` (manifest interchange) and
``<corpus>/lean_report.json``. Witness sources go to a scratch directory (they are a
deterministic function of the corpus and are regenerated by every check)."""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from . import INTERCHANGE_SCHEMA, SCHEMA_VERSION, DatagenError
from .generate import file_sha256, load_samples
from .records import mirror_action, mirror_observation
from .spec import get_family, to_fixed
from ..config import ROOT

LEAN_DIR = ROOT / "lean"
FORMAL_CONSTANTS = ("obstacle_inset_m", "min_obstacle_width_m", "radius_margin_m")
SPLIT_INDEX = {"train": 0, "val": 1, "test": 2}
MIRROR_SAMPLES_PER_RUN = 3
ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


def _spec(family) -> dict:
    return {"name": family.name, "version": family.version,
            "factors": [{"name": f.name, "levels": list(f.levels),
                         "bins": [{"label": b.label, "lo": to_fixed(b.lo), "hi": to_fixed(b.hi),
                                   "hiInclusive": b.hi_inclusive} for b in f.bins]} for f in family.factors],
            "nuisance": [{"name": n.name, "lo": to_fixed(n.lo), "hi": to_fixed(n.hi)} for n in family.nuisance],
            "constants": [[k, to_fixed(family.constants[k])] for k in FORMAL_CONSTANTS]}


def _scenario(family, e: dict) -> dict | None:
    if e.get("scenario_id") is None:  # schema-level rejection: parameters not representable
        return None
    c = family.canonical_params(e["params"])
    return {"id": e["scenario_id"], "hash": int(e["scenario_sha256"], 16), "family": e["family"],
            "familyVersion": e["family_version"],
            "nums": [[f.name, c[f.name]] for f in family.factors if f.numeric] + [[n.name, c[n.name]] for n in family.nuisance],
            "cats": [[f.name, c[f.name]] for f in family.factors if not f.numeric],
            "bins": [[k, v] for k, v in e["bins"].items() if v is not None],
            "accepted": e["status"] == "accepted",
            "formalRejected": any(r.startswith("formal:") for r in e["rejection_reasons"]),
            "split": e.get("split", ""), "group": e.get("group_id", ""), "region": e.get("region", "")}


def _fx(x) -> int:
    return int(round(float(x) * 1_000_000))


def _pts(p) -> list:
    return [[_fx(a), _fx(b)] for a, b in p]


def obs_m(o: dict) -> dict:
    """Label-relevant part of a POLICY observation in 1e-6 fixed point (mirror check only)."""
    r = o["road"]
    return {"lateral": _fx(r["lateral_offset"]), "heading": _fx(r["heading_error"]), "curvature": _fx(r["curvature"]),
            "widthLeft": _fx(r["width_left"]), "widthRight": _fx(r["width_right"]),
            "distLeft": _fx(r["dist_to_left_boundary"]), "distRight": _fx(r["dist_to_right_boundary"]),
            "vy": _fx(o["vy"]), "yawRate": _fx(o["yaw_rate"]), "ay": _fx(o["ay"]), "steer": _fx(o["steer"]),
            "previewCurvature": [_fx(v) for v in r["preview_curvature"]],
            "previewWidthLeft": [_fx(v) for v in r["preview_width_left"]],
            "previewWidthRight": [_fx(v) for v in r["preview_width_right"]],
            "centerline": _pts(r["preview_centerline"]), "leftBoundary": _pts(r["preview_left_boundary"]),
            "rightBoundary": _pts(r["preview_right_boundary"]),
            "obstacles": [{"dist": _fx(b["distance"]), "latMin": _fx(b["lateral_min"]), "latMax": _fx(b["lateral_max"])}
                          for b in r["obstacles"]]}


def act_m(a: dict) -> dict:
    return {"steer": _fx(a["steer"]), "throttle": _fx(a["throttle"]), "brake": _fx(a["brake"]),
            "path": _pts(a["path"] or [])}


def export(manifest: dict, out: Path, index: dict | None = None, corpus: Path | None = None) -> Path:
    """Write the manifest interchange (+ corpus-level claims the checker compares against)."""
    family = get_family(manifest["family_spec"]["name"])
    out.mkdir(parents=True, exist_ok=True)
    for stale in ("certs",):  # v1.0.0 layout: certificates are now read from the samples themselves
        if (out / stale).exists():
            shutil.rmtree(out / stale)
    pol = manifest["split_policy"]
    inter = {
        "schema": INTERCHANGE_SCHEMA, "schemaVersion": SCHEMA_VERSION, "spec": _spec(family),
        "strength": manifest["required_coverage"]["strength"],
        "splitPolicy": {"regionFactors": pol["region_factors"],
                        "regions": [{"split": sp, "cell": [[k, v] for k, v in reg.items()]}
                                    for sp in ("val", "test") for reg in pol.get("regions", {}).get(sp, []) or []]},
        "scenarios": [x for x in (_scenario(family, e) for e in manifest["scenarios"]) if x is not None],
        "pairs": [{"base": p["base_id"], "variant": p["variant_id"], "factor": p["factor"]} for p in manifest["contrast_pairs"]],
        "requiredCells": manifest["required_coverage"]["cells"], "manifestMissing": manifest["coverage"]["missing"],
        "hasCorpus": index is not None, "backend": index["backend"]["name"] if index else "",
        "realisedClean": [], "realisedMissing": [], "cleanSamples": [], "mirrorChecks": [],
    }
    if index is not None:
        inter["realisedClean"] = [s["scenario_id"] for s in index["scenarios"] if s.get("clean_run") and s.get("n_clean", 0) > 0]
        inter["realisedMissing"] = index["coverage_realised"]["missing"]
        hashes = []
        for run in index["scenarios"]:
            if run.get("status") != "completed":
                continue
            mirrors = []
            for s in load_samples(corpus / run["files"]["samples"]["path"]):
                if not s["quality"]["clean"]:
                    continue
                hashes.append((int(s["hashes"]["content"], 16), SPLIT_INDEX[s["split"]]))
                po = s["policy_observation"]
                if len(mirrors) < MIRROR_SAMPLES_PER_RUN and po["road"] and po["road"]["obstacles"]:
                    act = s["target"]["uncertified"]
                    mirrors.append({"sampleId": s["sample_id"], "obs": obs_m(po), "act": act_m(act),
                                    "mirroredObs": obs_m(mirror_observation(po)), "mirroredAct": act_m(mirror_action(act))})
            inter["mirrorChecks"] += mirrors
        inter["cleanSamples"] = [list(h) for h in sorted(hashes)]
    ip = out / "interchange.json"
    ip.write_text(json.dumps(inter, separators=(",", ":")))
    return ip


def lake_path() -> str:
    exe = shutil.which("lake") or str(Path.home() / ".elan" / "bin" / ("lake.exe" if os.name == "nt" else "lake"))
    if not Path(exe).exists():
        raise DatagenError("Lean 4 build tool 'lake' not found. Install elan (https://github.com/leanprover/elan); the "
                           "toolchain is pinned in lean/lean-toolchain.")
    return exe


def build() -> str:
    lake = lake_path()
    b = subprocess.run([lake, "build"], cwd=LEAN_DIR, capture_output=True, text=True)
    if b.returncode != 0:
        raise DatagenError(f"lake build failed:\n{b.stdout[-3000:]}\n{b.stderr[-2000:]}")
    return lake


_AX = re.compile(r"^'([^']+)' (?:depends on axioms: \[([^\]]*)\]|does not depend on any axioms)")


def parse_axioms(text: str) -> dict[str, set[str]]:
    out = {}
    for ln in text.splitlines():
        m = _AX.match(ln.strip())
        if m:
            out[m.group(1)] = {a.strip() for a in (m.group(2) or "").split(",") if a.strip()}
    return out


def axiom_audit(lake: str) -> dict:
    """Release gate: every theorem named in Corpus/Audit.lean is reported and uses only the
    standard axioms."""
    src = (LEAN_DIR / "Corpus" / "Audit.lean").read_text()
    wanted = re.findall(r"^#print axioms (\S+)", src, re.M)
    r = subprocess.run([lake, "env", "lean", "Corpus/Audit.lean"], cwd=LEAN_DIR, capture_output=True, text=True)
    got = parse_axioms(r.stdout)
    missing = [t for t in wanted if t not in got]
    bad = {t: sorted(ax - ALLOWED_AXIOMS) for t, ax in got.items() if ax - ALLOWED_AXIOMS}
    ok = r.returncode == 0 and not missing and not bad and len(wanted) > 0
    return {"ok": ok, "theorems": len(wanted), "allowed_axioms": sorted(ALLOWED_AXIOMS), "missing": missing,
            "non_standard": bad, "lines": [ln for ln in r.stdout.splitlines() if ln.strip()],
            "stderr": r.stderr[-2000:]}


def _check_witness_file(lake: str, path: Path) -> dict:
    src = path.read_text(encoding="utf-8")
    names = re.findall(r"^theorem (s\d+) ", src, re.M)
    r = subprocess.run([lake, "env", "lean", str(path)], cwd=LEAN_DIR, capture_output=True, text=True)
    ax = parse_axioms(r.stdout)
    ns = path.stem
    proved = [n for n in names if f"{ns}.{n}" in ax]
    bad = [n for n in proved if ax[f"{ns}.{n}"] - ALLOWED_AXIOMS]
    errors = [ln for ln in r.stdout.splitlines() if ": error" in ln][:5]
    return {"file": path.name, "theorems": len(names), "proved": len(proved), "bad_axioms": bad,
            "returncode": r.returncode, "errors": errors,
            "ok": r.returncode == 0 and len(proved) == len(names) and not bad and not errors}


def kernel_witnesses(lake: str, wdir: Path, expected_ids: list[str], jobs: int | None = None,
                     *, lateral: bool = False) -> dict:
    """Kernel-check every longitudinal or lateral witness file and exact clean id set."""
    idx_name = "witness_index_lateral.json" if lateral else "witness_index.json"
    prefix = "WitnessL_" if lateral else "Witness_"
    idx = json.loads((wdir / idx_name).read_text())
    files = sorted(wdir.glob(f"{prefix}*.lean"), key=lambda p: int(p.stem.split("_")[1]))
    with ThreadPoolExecutor(max_workers=jobs or max(1, (os.cpu_count() or 2) - 1)) as ex:
        res = list(ex.map(lambda p: _check_witness_file(lake, p), files))
    ids = [w["sample_id"] for w in idx]
    proved = sum(r["proved"] for r in res)
    ok = (all(r["ok"] for r in res) and proved == len(ids) and sorted(ids) == sorted(expected_ids)
          and len(set(ids)) == len(ids) and len(ids) > 0)
    h = hashlib.sha256()
    for p in files:
        h.update(p.read_bytes())
    return {"ok": ok, "method": "one theorem per clean sample, proved by decide (Lean kernel)",
            "files": len(files), "theorems": len(ids), "kernel_proved": proved,
            "expected_clean_samples": len(expected_ids), "ids_equal_expected": sorted(ids) == sorted(expected_ids),
            "witness_sources_sha256": h.hexdigest(), "failed_files": [r for r in res if not r["ok"]][:10]}


def _clean_ids(corpus: Path, index: dict) -> list[str]:
    out = []
    for run in index["scenarios"]:
        if run.get("status") == "completed":
            out += [s["sample_id"] for s in load_samples(corpus / run["files"]["samples"]["path"]) if s["quality"]["clean"]]
    return out


def run_checker(interchange: Path, corpus: Path | None, report_path: Path, *, witness: bool = True,
                witness_dir: Path | None = None, jobs: int | None = None) -> dict:
    lake = build()
    exe = LEAN_DIR / ".lake" / "build" / "bin" / ("corpuscheck.exe" if os.name == "nt" else "corpuscheck")
    tmp = None
    args = [str(exe)]
    if corpus is not None and witness:
        if witness_dir is None:
            tmp = tempfile.mkdtemp(prefix="corpus-witness-")
            witness_dir = Path(tmp)
        elif witness_dir.exists():
            shutil.rmtree(witness_dir)
        args += ["--witness", str(witness_dir)]
    args += [str(interchange)] + ([str(corpus)] if corpus is not None else [])
    try:
        r = subprocess.run(args, capture_output=True, text=True)
        if r.returncode not in (0, 1):
            raise DatagenError(f"corpuscheck failed ({r.returncode}): {r.stderr[-2000:]}")
        report = json.loads(r.stdout)
        report["axiom_audit"] = axiom_audit(lake)
        if not report["axiom_audit"]["ok"]:
            report["ok"] = False
        if corpus is not None:
            if witness:
                index = json.loads((corpus / "index.json").read_text())
                expected = _clean_ids(corpus, index)
                report["kernel_witnesses"] = kernel_witnesses(lake, witness_dir, expected, jobs)
                report["kernel_witnesses_lateral"] = kernel_witnesses(
                    lake, witness_dir, expected, jobs, lateral=True)
                if not report["kernel_witnesses"]["ok"] or not report["kernel_witnesses_lateral"]["ok"]:
                    report["ok"] = False
            else:
                report["kernel_witnesses"] = {"ok": None, "skipped": True}
                report["kernel_witnesses_lateral"] = {"ok": None, "skipped": True}
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)
    report["toolchain"] = (LEAN_DIR / "lean-toolchain").read_text().strip()
    report["checker_binary_sha256"] = file_sha256(exe)
    report["inputs"] = {"interchange": str(interchange), "interchange_sha256": file_sha256(interchange),
                        "corpus": str(corpus) if corpus else None,
                        "index_sha256": file_sha256(corpus / "index.json") if corpus else None}
    report["lean_sources_sha256"] = {str(p.relative_to(LEAN_DIR)).replace(os.sep, "/"): file_sha256(p)
                                     for p in sorted(LEAN_DIR.glob("**/*.lean")) if ".lake" not in p.parts}
    report_path.write_text(json.dumps(report, indent=1))
    return report


def main_lean(a) -> int:
    target = Path(a.target)
    try:
        if target.is_dir():
            index = json.loads((target / "index.json").read_text())
            manifest = json.loads((target / "manifest.json").read_text())
            ip = export(manifest, target / "lean", index, target)
            report = run_checker(ip, target, target / "lean_report.json", witness=not a.no_witness, jobs=a.jobs)
            report_path = target / "lean_report.json"
        else:
            manifest = json.loads(target.read_text())
            out = Path(a.out) if a.out else target.with_suffix(".lean")
            ip = export(manifest, out)
            report_path = out / "lean_report.json"
            report = run_checker(ip, None, report_path)
    except DatagenError as e:
        print(f"data-lean: {e}")
        return 3
    for r in report["results"]:
        print(f"  [{'ok' if r['ok'] else 'FAIL'}] {r['name']:<42} {r['basis']}" + (f"\n        {r['detail']}" if r["detail"] else ""))
    au = report["axiom_audit"]
    print(f"  axiom audit: {'OK' if au['ok'] else 'FAILED'} ({au['theorems']} theorems, standard axioms only)"
          + ("" if au["ok"] else f" missing={au['missing']} non_standard={au['non_standard']}"))
    kw = report.get("kernel_witnesses")
    if kw:
        print(f"  kernel witnesses: " + ("skipped (--no-witness)" if kw.get("skipped") else
              f"{'OK' if kw['ok'] else 'FAILED'} ({kw['kernel_proved']}/{kw['expected_clean_samples']} clean samples "
              f"proved by the kernel in {kw['files']} files)"))
    print(json.dumps(report["stats"]))
    print(f"{'OK' if report['ok'] else 'FAILED'} (Lean {report['lean_version']}, backend '{report['backend'] or 'n/a'}') "
          f"-> {report_path}")
    return 0 if report["ok"] else 1
